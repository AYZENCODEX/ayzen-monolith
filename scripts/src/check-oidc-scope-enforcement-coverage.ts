/**
 * scripts/src/check-oidc-scope-enforcement-coverage.ts
 * ─────────────────────────────────────────────────────────────────────────────
 * AYZEN Enforcement Roadmap — Track G, Phase G3 ("OIDC scope/consent
 * enforcement at the route layer").
 *
 * ── Why this exists ─────────────────────────────────────────────────────────
 * `lib/oidc-scope-enforcement.ts`'s `requireOidcScope()` (Phase 4d) and
 * `lib/oidc-consent-scope-superset.ts`'s `evaluateScopeCreep()` (Phase 7e)
 * were both real, unit-tested, IMPORTABLE functions — but nothing checked
 * that every route that should call them actually does. `routes/oidc-
 * userinfo.ts` (4c-f) was exactly that gap in practice: it hand-rolled its
 * own bearer extraction + `verifyOidcAccessToken()` + revocation check
 * inline (duplicating `requireOidcScope()`'s own body) and never checked
 * the token's granted scopes at all, so any cryptographically-valid,
 * non-revoked access token — regardless of scope — could read UserInfo.
 * Fixed in the same pass this script shipped in (see
 * `docs/changes/CHANGES_ENFORCEMENT_ROADMAP_TRACK_G_PHASE_G3.md`). This is
 * the regression gate so the next resource route doesn't reintroduce it.
 *
 * ── Why this ISN'T an extension of `validate-domain-contract-coverage.mjs`
 *    (Phase F4), despite the roadmap's own G3 text suggesting that ────────
 * The Phase F4 validator operates entirely on `ENDPOINT_REGISTRY`
 * (`packages/endpoint-registry`), which is itself generated by
 * `tools/domain-routing/generate-endpoint-registry.mjs` (Phase F1) by
 * scanning ONLY the route files mounted through `routes/index.ts`'s
 * `router.use(...)` calls, and unconditionally prefixing every path it
 * finds with `/api`. Every bare-origin `/oidc/*` router (`oidc-userinfo.ts`,
 * `oidc-resource.ts`, and the rest) is mounted directly in `app.ts`
 * instead — deliberately, per each of those files' own headers, since an
 * OIDC client builds these URLs directly against the issuer's origin, not
 * through `/api`. That means NONE of them appear in `ENDPOINT_REGISTRY` at
 * all today, under any auth mode — there is no `"user"`/`"admin"` entry
 * for `/oidc/userinfo` to extend F4's check onto. Teaching the F1 scanner
 * to also read `app.ts`'s bare mounts, invent a non-`/api` path shape, AND
 * infer a new OIDC-specific auth mode the whole rest of the registry
 * doesn't have a concept of would be a materially bigger change than this
 * phase's own stated scope ("confirm... at the route layer") calls for —
 * and would still need this file's own bearer-vs-session distinction to
 * classify correctly, since `inferMonolithAuth()`'s `requireAuth`/
 * `requireAdmin`-based heuristic has no way to recognize
 * `requireOidcScope()` as a THIRD, bearer-token auth mode distinct from
 * both. So: a small, standalone, purpose-built check instead, following
 * this codebase's own established pattern of a self-contained coverage
 * script per concern (`check-ownership-gate-coverage.ts` for the ownership
 * gate, `validate-domain-contract-coverage.mjs` for domain ownership) —
 * not a workaround, but the same "narrow, purpose-built checker" shape
 * those two already use, applied to a concern the generated registry
 * structurally cannot see yet. A future pass that teaches F1 to model
 * bare-origin bearer-token routes could fold this in; not attempted here
 * (would be scope creep on this phase, same "no speculative implementation
 * of future phases" discipline the rest of this roadmap already follows).
 *
 * ── What this checks, precisely ─────────────────────────────────────────
 * Two checks, both over every `artifacts/api-server/src/routes/oidc-*.ts`
 * file (the full bare-origin OIDC route surface — see `RESOURCE_ROUTE_
 * FILES` below for why this glob, not `app.ts`'s mount list, is the scan
 * root):
 *
 *   1. REGRESSION GUARD (self-classifying, repo-wide, no allowlist to
 *      maintain): no `routes/oidc-*.ts` file may import
 *      `verifyOidcAccessToken` from `../lib/oidc-access-token-verification`
 *      directly. That's the low-level primitive `requireOidcScope()`
 *      itself wraps (extraction + verification + revocation-check,
 *      composed once, correctly, in one place) — a route importing it
 *      directly is re-implementing bearer-token gating inline instead of
 *      going through the shared middleware, which is the exact shape of
 *      bug this phase fixed. After this pass, zero route files do this
 *      (`oidc-resource.ts` never did; `oidc-userinfo.ts` no longer does) —
 *      this check keeps it at zero.
 *
 *   2. COVERAGE CHECK (small, reviewed allowlist — same "tiny, hand-
 *      reviewed exception list" shape `OWNER_ALIASES` in the F4 validator
 *      and `SEED_ENTRIES` in the F1 generator already use): for each file
 *      in `RESOURCE_ROUTE_FILES` below — today, `oidc-userinfo.ts` and
 *      `oidc-resource.ts`, the only two files that mount an actual
 *      bearer-token OIDC resource endpoint (see each file's own header for
 *      why the rest of the bare-origin `/oidc/*` surface is a PROTOCOL
 *      endpoint — session-cookie or client-credential authenticated, not a
 *      resource route a bearer access token's scope should gate) — every
 *      `router.<verb>("/oidc/...", ...)` call in that file must have
 *      `requireOidcScope(` appear somewhere in its own middleware/handler
 *      argument list. A resource route added to one of these two files
 *      without it fails; a new file added to `RESOURCE_ROUTE_FILES` is a
 *      deliberate, reviewed, one-line addition (same as this list's other
 *      two entries), not something this script infers on its own — mis-
 *      classifying a genuine resource route as "protocol" is exactly the
 *      failure mode a silent auto-classifier would risk.
 *
 * Deliberately NOT covered (see file's own future-work note above): this
 * does not check that `evaluateScopeCreep()` (7e) is invoked — that's
 * confirmed by hand for the two call sites that exist today (`oidc-
 * authorize.ts`, `oidc-consent.ts`; see this phase's CHANGES doc) since
 * unlike `requireOidcScope()` it's a pure comparison called from within
 * handler bodies, not Express middleware with a structurally-checkable
 * call-site shape the way `router.<verb>(...)`'s argument list is. A
 * future pass could add an AST-based "is this function called anywhere in
 * this file" check the same way `check-ownership-gate-coverage.ts` traces
 * its own PEP wrapper functions; not attempted here to keep this pass's
 * surface to what G3 actually found a live gap in.
 *
 * ── Usage ────────────────────────────────────────────────────────────────
 *   tsx scripts/src/check-oidc-scope-enforcement-coverage.ts
 *     Exits 1 and prints every violation found; exits 0 (silently, past a
 *     one-line summary) otherwise. No baseline file — unlike Track H's
 *     89-route ownership gap or F4's domain-contract drift, this surface
 *     is two files and one known-fixed bug, not a large pre-existing
 *     backlog that needs grandfathering to avoid blocking unrelated work.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(__dirname, "..", "..");
const ROUTES_DIR = path.join(repoRoot, "artifacts/api-server/src/routes");

// The only bare-origin `/oidc/*` route files that mount an actual bearer-
// token-gated resource endpoint, as of this pass. See file header (check
// 2) for why this is a small, hand-reviewed list rather than inferred.
const RESOURCE_ROUTE_FILES = ["oidc-userinfo.ts", "oidc-resource.ts"];

const ROUTE_CALL_RE = /router\.(get|post|put|patch|delete)\(\s*["']([^"']+)["']/g;
const DIRECT_VERIFY_IMPORT_RE =
  /import\s*\{[^}]*\bverifyOidcAccessToken\b[^}]*\}\s*from\s*["']\.\.\/lib\/oidc-access-token-verification["']/;

function oidcRouteFiles(): string[] {
  return fs
    .readdirSync(ROUTES_DIR)
    .filter((name) => name.startsWith("oidc-") && name.endsWith(".ts"))
    .sort();
}

interface Violation {
  file: string;
  reason: string;
}

const violations: Violation[] = [];

for (const file of oidcRouteFiles()) {
  const filePath = path.join(ROUTES_DIR, file);
  const source = fs.readFileSync(filePath, "utf8");

  // Check 1 — regression guard, every file.
  if (DIRECT_VERIFY_IMPORT_RE.test(source)) {
    violations.push({
      file,
      reason:
        "imports verifyOidcAccessToken directly from lib/oidc-access-token-verification " +
        "instead of going through requireOidcScope() (lib/oidc-scope-enforcement.ts) — " +
        "hand-rolled bearer-token verification duplicates and can drift from the shared " +
        "middleware's extraction/verification/revocation-check/scope-check chain.",
    });
  }

  // Check 2 — coverage check, resource-route files only.
  if (!RESOURCE_ROUTE_FILES.includes(file)) continue;

  const calls = [...source.matchAll(ROUTE_CALL_RE)];
  for (let i = 0; i < calls.length; i += 1) {
    const call = calls[i];
    const method = call[1].toUpperCase();
    const routePath = call[2];
    const sliceEnd = i + 1 < calls.length ? calls[i + 1].index : source.length;
    const callSlice = source.slice(call.index, sliceEnd);
    if (!callSlice.includes("requireOidcScope(")) {
      violations.push({
        file,
        reason: `${method} ${routePath} does not have requireOidcScope(...) in its middleware chain`,
      });
    }
  }
}

if (violations.length > 0) {
  console.error(`OIDC scope-enforcement coverage: ${violations.length} violation(s) found.\n`);
  for (const v of violations) {
    console.error(`  [FAIL] ${v.file}: ${v.reason}`);
  }
  console.error(
    "\nEvery bearer-token OIDC resource route must be gated with requireOidcScope() " +
      "(lib/oidc-scope-enforcement.ts), not hand-rolled verification. If this is a genuinely " +
      "new resource-route file (not a regression), add it to RESOURCE_ROUTE_FILES in this " +
      "script once its routes are correctly gated.",
  );
  process.exit(1);
}

console.log(
  `OIDC scope-enforcement coverage: ${oidcRouteFiles().length} route file(s) scanned, ` +
    `${RESOURCE_ROUTE_FILES.length} resource-route file(s) checked for requireOidcScope() coverage, ` +
    "0 violations.",
);
