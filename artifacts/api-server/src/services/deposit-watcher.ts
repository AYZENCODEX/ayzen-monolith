export interface ChainConfig {
  chain: string;         // matches wallets.chain / networks.chain
  rpcUrl: string;
  chainId: number;
  nativeSymbol: string;
  confirmationsRequired: number;
  blockRangePerPoll: number; // safety cap so one poll never scans an unbounded range
  /** ERC-20 stablecoins to watch for on this chain. */
  tokens: { symbol: string; contract: string; decimals: number }[];
}

// ERC-20s watched per chain, sourced from lib/tokens.ts so this list can
// never drift out of sync with the withdrawal-side resolver.
function erc20sFor(chain: string): { symbol: string; contract: string; decimals: number }[] {
  return tokensForChain(chain)
    .filter((t) => !t.isNative && t.contract)
    .map((t) => ({ symbol: t.symbol, contract: t.contract!, decimals: t.decimals }));
}

