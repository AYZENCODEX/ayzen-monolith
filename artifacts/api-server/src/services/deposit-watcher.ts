/**
 * services/deposit-watcher.ts
 * ─────────────────────────────────────────────────────────────────────────────
 * Real-time deposit detection for the AYZEN vault wallet across five EVM
 * chains: Ethereum (ETH), BNB Chain (BNB), Polygon (POL), Plasma (XPL), and
 * Arbitrum (ETH gas + the separate ARB token). Every chain's `tokens` list
 * (USDT everywhere, USDC on ETH/BSC/MATIC/ARB, plus ARB on Arbitrum) is
 * watched for ERC-20 deposits alongside the native coin — this list is
 * entirely driven by lib/tokens.ts, so adding a new token/chain row there
 * is all that's needed for the watcher to pick it up. The custodial wallet
 * address generated by
 * POST /wallets/builtin/create is the SAME address on every one of these
 * chains (one EVM keypair), so a user only ever needs to be shown one
 * deposit address + a network picker.
 *
 * How it works (poll-based, since free public RPCs don't offer reliable
 * WebSocket subscriptions):
 *   1. Every POLL_INTERVAL_MS, for each chain: read the latest block number
 *      and scan every block since the last cursor for (a) native-coin
 *      transfers whose `to` is a tracked wallet address, and (b) ERC-20
 *      Transfer logs (via eth_getLogs — cheap, no full block fetch needed)
 *      for the chain's configured stablecoin contract(s) whose `to` topic
 *      is a tracked address.
 *   2. The instant a matching tx/log is seen, it's written to
 *      chain_deposits as `status: 'pending'` and broadcast over SSE
 *      (`deposit_detected`) — this is the "real-time" part, usually a few
 *      seconds after the tx lands.
 *   3. On each subsequent poll, pending deposits have their `confirmations`
 *      recomputed from the current chain height. Once a deposit crosses the
 *      chain's required confirmation count, its amount is credited to the
 *      user (native → that wallet row's `balance`; stablecoin → the
 *      `builtin_wallet_tokens` ledger) and marked `credited` + `confirmed`,
 *      broadcasting `deposit_confirmed`.
 *
 * This mirrors the existing withdrawal path (routes/wallets.ts
 * handleWithdraw): withdrawals sign + broadcast outbound, this service
 * watches inbound — together they're the vault wallet's full deposit/
 * withdrawal loop.
 */
